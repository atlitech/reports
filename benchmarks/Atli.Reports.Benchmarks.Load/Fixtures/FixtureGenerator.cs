    );
    return html.ToString();
  }

  private static string Png(int width, int height, Func<int, int, (byte, byte, byte)> pixel) =>
    "data:image/png;base64," + Convert.ToBase64String(StoredPng.Encode(width, height, pixel));

  private static (byte, byte, byte) Banner(int x, int y)
  {
    // Sky gradient over rolling hills.
    var hill = 70 + (18 * Math.Sin(x / 37.0)) + (9 * Math.Sin(x / 11.0));
    if (y > hill)
    {
      var shade = (y - hill) / (120 - hill + 1);
      return (Clamp(40 + (30 * shade)), Clamp(110 - (40 * shade)), Clamp(60 - (20 * shade)));
    }

    return (Clamp(120 + (x / 8.0)), Clamp(170 + (y / 2.0)), 235);
  }

  private static (byte, byte, byte) Photo(
    int x,
    int y,
    int width,
    int height,
    int seed,
    (int R, int G, int B) hue
  )
  {
    var light =
      0.55 + (0.35 * (1 - ((double)y / height))) + (0.1 * Math.Sin((x + (seed * 40)) / 23.0));
    var noise = (Hash(x, y, seed) & 0x1F) - 16;
    var vignette = 1 - (0.35 * Math.Pow(((double)x / width) - 0.5, 2) * 4);
    return (
      Clamp((hue.R * light * vignette) + noise),
      Clamp((hue.G * light * vignette) + noise),
      Clamp((hue.B * light * vignette) + noise)
    );
  }

  private static (byte, byte, byte) Thumbnail(int x, int y, int index)
  {
    var stripe = ((x + (y * (index + 1))) / 8) % 2 == 0;
    var noise = (Hash(x, y, index + 10) & 0x0F) - 8;
    var baseColor = 90 + (index * 25);
    return stripe
      ? (Clamp(baseColor + noise), Clamp(200 - baseColor + noise), Clamp(160 + noise))
      : (Clamp(60 + noise), Clamp(70 + noise), Clamp(80 + (index * 10) + noise));
  }

  private static int Hash(int x, int y, int seed)
  {
    unchecked
    {
      var h = (uint)((x * 73_856_093) ^ (y * 19_349_663) ^ (seed * 83_492_791));
      h ^= h >> 13;
      h *= 0x5bd1e995;
      h ^= h >> 15;
      return (int)(h & 0x7FFFFFFF);
    }
  }

  private static byte Clamp(double value) => (byte)Math.Clamp(Math.Round(value), 0, 255);

  private static string Pick(string[] values, DeterministicRandom random) =>
    values[random.Next(values.Length)];

  /// <summary>
  /// A small xorshift generator; unlike <see cref="Random"/>, its sequence is fixed by this code.
  /// </summary>
  private sealed class DeterministicRandom(uint seed)
  {
    private uint _state = seed == 0 ? 0x9E3779B9u : seed;

    public int Next(int maxExclusive) => (int)(NextUInt() % (uint)maxExclusive);

    public double NextDouble() => NextUInt() / 4_294_967_296.0;

    private uint NextUInt()
    {
      var x = _state;
      x ^= x << 13;
      x ^= x >> 17;
      x ^= x << 5;
      _state = x;
      return x;
    }
  }
}
