        </head>
        <body>
          <img class="banner" alt="Site overview" src="{{banner}}" />
          <h1>Site inspection report — Building C</h1>
          <p>Inspection date 2026-09-29 · Inspector: J. Rivera · Reference SIR-2026-117</p>
          <h2>Summary</h2>
          <p>
