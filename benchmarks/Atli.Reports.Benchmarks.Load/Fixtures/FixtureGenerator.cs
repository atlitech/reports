using System.Globalization;
using System.Text;

namespace Atli.Reports.Benchmarks.Load.Fixtures;

/// <summary>
/// Writes the two generated fixtures, <c>long-table.html</c> and <c>assets.html</c>.
/// </summary>
/// <remarks>
/// The output is deterministic: the same code always writes the same bytes, so regenerating the
/// fixtures never changes the workload by accident. <c>invoice.html</c> and <c>chart.html</c> are
/// written by hand and are not generated.
/// </remarks>
internal static class FixtureGenerator
{
  /// <summary>
  /// Rows in the long table; with 20 px rows this paginates to about 50 A4 pages.
  /// </summary>
  public const int LongTableRows = 2_400;

  private const string Font = "\"Liberation Sans\", Arial, Helvetica, sans-serif";

  private static readonly string[] Accounts =
  [
    "4000 Revenue",
    "4100 Services",
    "5000 Cost of sales",
    "6100 Payroll",
    "6200 Rent",
    "6300 Utilities",
    "6400 Travel",
    "6500 Software",
    "6600 Marketing",
    "7000 Interest",
  ];

  private static readonly string[] Descriptions =
  [
    "Monthly subscription renewal",
    "Consulting hours — analytics",
    "Office supplies",
    "Cloud storage — standard tier",
    "Conference registration",
    "Hardware lease payment",
    "Contractor invoice",
    "Customer refund",
    "Bank service charge",
    "Freight and delivery",
    "Licence true-up",
    "Facilities maintenance",
  ];

  private static readonly string[] CostCentres = ["NA-01", "NA-02", "EU-01", "EU-02", "APAC-1"];

  /// <summary>
  /// Writes the generated fixtures into <paramref name="directory"/>.
  /// </summary>
  /// <returns>The paths written.</returns>
  public static IReadOnlyList<string> Generate(string directory)
  {
    Directory.CreateDirectory(directory);
    var longTable = Path.Combine(directory, "long-table.html");
    var assets = Path.Combine(directory, "assets.html");
    UTF8Encoding utf8 = new(encoderShouldEmitUTF8Identifier: false);
    File.WriteAllText(longTable, BuildLongTable(), utf8);
    File.WriteAllText(assets, BuildAssets(), utf8);
    return [longTable, assets];
  }

  private static string BuildLongTable()
  {
    var random = new DeterministicRandom(2026);
    StringBuilder html = new(capacity: 400_000);
    html.Append(
      $$"""
      <!doctype html>
      <html lang="en">
        <head>
          <meta charset="utf-8" />
          <title>General ledger detail — FY2026</title>
          <!--
            Benchmark fixture "long-table" (generated by `Atli.Reports.Benchmarks.Load generate-fixtures`;
            do not edit by hand). A {{LongTableRows}}-row ledger with fixed 20 px rows and a repeating
            header, which paginates to about 50 A4 pages. Fully self-contained.
          -->
          <style>
            @page { size: A4; }
            body { margin: 0; font-family: {{Font}}; font-size: 8.5pt; color: #1f2933; }
            h1 { margin: 0 0 4px; font-size: 16pt; color: #0f4c81; }
            p.subtitle { margin: 0 0 10px; color: #52606d; }
            table { width: 100%; border-collapse: collapse; table-layout: fixed; }
            thead { display: table-header-group; }
            th { background: #0f4c81; color: #fff; text-align: left; padding: 4px 6px; font-size: 8pt; }
            tr { height: 20px; break-inside: avoid; }
            td { padding: 0 6px; border-bottom: 1px solid #e4e7eb; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }
            tbody tr:nth-child(even) td { background: #f8fafc; }
            .n { text-align: right; font-variant-numeric: tabular-nums; }
            tfoot td { font-weight: bold; border-top: 2px solid #0f4c81; }
          </style>
        </head>
        <body>
          <h1>General ledger detail — FY2026</h1>
          <p class="subtitle">Northwind Analytics LLC · All cost centres · {{LongTableRows}} entries</p>
          <table>
            <colgroup><col style="width:7%"><col style="width:10%"><col style="width:16%"><col><col style="width:9%"><col style="width:6%"><col style="width:10%"><col style="width:11%"></colgroup>
            <thead><tr><th>Entry</th><th>Date</th><th>Account</th><th>Description</th><th>Centre</th><th class="n">Qty</th><th class="n">Unit</th><th class="n">Amount</th></tr></thead>
            <tbody>

      """
    );

    decimal total = 0;
    var date = new DateOnly(2026, 1, 1);
    for (var row = 1; row <= LongTableRows; row++)
    {
      if (random.Next(3) == 0)
      {
        date = date.AddDays(1);
      }

      var quantity = 1 + random.Next(40);
      var unit = Math.Round((decimal)(5 + (random.NextDouble() * 495)), 2);
      var amount = quantity * unit;
      total += amount;
      html.Append(
        CultureInfo.InvariantCulture,
        $"<tr><td>JE-{row:D5}</td><td>{date:yyyy-MM-dd}</td><td>{Pick(Accounts, random)}</td>"
          + $"<td>{Pick(Descriptions, random)}</td><td>{Pick(CostCentres, random)}</td>"
          + $"<td class=\"n\">{quantity}</td><td class=\"n\">{unit:N2}</td><td class=\"n\">{amount:N2}</td></tr>\n"
      );
    }

    html.Append(
      CultureInfo.InvariantCulture,
      $"""
          </tbody>
          <tfoot><tr><td colspan="7">Total ({LongTableRows} entries)</td><td class="n">{total:N2}</td></tr></tfoot>
        </table>
      </body>
      </html>

      """
    );
    return html.ToString();
  }

  private static string BuildAssets()
  {
    var banner = Png(640, 120, Banner);
    string[] photos =
    [
      Png(320, 200, (x, y) => Photo(x, y, 320, 200, seed: 1, hue: (90, 140, 200))),
      Png(320, 200, (x, y) => Photo(x, y, 320, 200, seed: 2, hue: (200, 120, 60))),
      Png(320, 200, (x, y) => Photo(x, y, 320, 200, seed: 3, hue: (60, 170, 110))),
      Png(320, 200, (x, y) => Photo(x, y, 320, 200, seed: 4, hue: (150, 90, 170))),
    ];
    var thumbnails = Enumerable
      .Range(0, 6)
      .Select(i => Png(112, 84, (x, y) => Thumbnail(x, y, i)))
      .ToArray();

    string[] areas = ["North façade", "Roof membrane", "Plant room", "Stairwell B"];
    string[] findings =
    [
      "Hairline cracking in render; monitor and re-inspect in 6 months.",
      "Ponding near the north-west outlet; clear debris and re-seal the upstand.",
      "Pump P-2 bearing noise above baseline; schedule maintenance.",
      "Emergency lighting test passed; signage faded on level 3.",
    ];

    StringBuilder html = new(capacity: 1_700_000);
    html.Append(
      $$"""
      <!doctype html>
      <html lang="en">
        <head>
          <meta charset="utf-8" />
          <title>Site inspection report — Building C</title>
          <!--
            Benchmark fixture "assets" (generated by `Atli.Reports.Benchmarks.Load generate-fixtures`;
            do not edit by hand). Every image is a PNG inlined as a base64 data URI, the way BlazorReports
            inlines report assets, so the HTML itself is ~1.6 MB. Fully self-contained.
          -->
          <style>
            @page { size: A4; }
            body { margin: 0; font-family: {{Font}}; font-size: 10pt; color: #1f2933; }
            .banner { display: block; width: 100%; height: auto; border-radius: 6px; }
            h1 { margin: 12px 0 2px; font-size: 18pt; color: #0f4c81; }
            h2 { margin: 18px 0 8px; font-size: 12pt; color: #0f4c81; border-bottom: 1px solid #d9e2ec; padding-bottom: 4px; }
            p { line-height: 1.45; }
            .photos { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; }
            figure { margin: 0; break-inside: avoid; }
            figure img { display: block; width: 100%; height: auto; border-radius: 4px; }
            figcaption { margin-top: 4px; font-size: 8.5pt; color: #52606d; }
            .thumbs { display: grid; grid-template-columns: repeat(3, 1fr); gap: 10px; }
            table { width: 100%; border-collapse: collapse; }
            th { text-align: left; background: #f0f4f8; padding: 6px; font-size: 9pt; }
            td { padding: 6px; border-bottom: 1px solid #e4e7eb; vertical-align: top; }
