            are embedded in this document so the report renders without network access.
          </p>
          <h2>Inspected areas</h2>
          <div class="photos">

      """
    );

    for (var i = 0; i < photos.Length; i++)
    {
      html.Append(
        CultureInfo.InvariantCulture,
        $"""
              <figure><img alt="{areas[i]}" src="{photos[i]}" /><figcaption>Figure {i + 1}. {areas[
          i
        ]}</figcaption></figure>

