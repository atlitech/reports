    );

    for (var i = 0; i < thumbnails.Length; i++)
    {
      html.Append(
        CultureInfo.InvariantCulture,
        $"""
              <figure><img alt="Detail {i + 1}" src="{thumbnails[i]}" /><figcaption>Detail {i
          + 1}</figcaption></figure>

