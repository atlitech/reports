namespace Atli.Reports.Engine;

/// <summary>
/// The orientation of PDF pages.
/// </summary>
public enum PageOrientation
{
  /// <summary>
  /// The paper's height is greater than its width.
  /// </summary>
  Portrait,

  /// <summary>
  /// The paper is rotated so its width is greater than its height.
  /// </summary>
  Landscape,
}
